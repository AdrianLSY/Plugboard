#!/usr/bin/env python3
"""Generator for the spine's directory indexes, in write mode and check mode.

Serves docs/knowledge-base -- "Generated indexes are checked in and cannot
drift": an index derived from other notes is produced by a tool, is tracked, is
byte-identical to a fresh regeneration, and declares both that it is generated
and which tool produces it.

The generator owns the comparison as well as the rendering. ci/gates/index_drift.py
calls `check()` here rather than reimplementing the diff, because a gate that
compares against its own second opinion of the expected bytes can pass while the
tool a contributor is told to run produces something else. One renderer, one
expectation, two entry points.

Determinism is the whole mechanism, so every degree of freedom is closed:

  * subjects come from _common.candidates -- the tracked index for a work tree --
    so an untracked scratch note never enters a tracked index;
  * notes are ordered by path, not by title, because two notes may share a title
    and a title is not a stable key;
  * a note with no H1 falls back to its filename stem rather than to nothing, so
    a missing heading changes one line instead of making output unstable;
  * output ends in exactly one trailing newline, and no field carries a
    timestamp, a hostname, a revision or a count that a rerun could change.

Write mode is the only mode that touches the filesystem. The gate never invokes
it -- a gate that repairs the state it inspects reports green over a defect.

Usage:
    python3 ci/gen/indexes.py --write [--root PATH]   # regenerate in place
    python3 ci/gen/indexes.py [--check] [--root PATH] # compare, exit 1 on drift

## What the violating input does not reach

`ci/generator-inputs/indexes/` holds one spine directory with two notes, and its pinned expectation
catches any change to the frontmatter block, the generated-by declaration, the heading, the link form
or the ordering. It does NOT reach: a note whose title is absent or not an H1; a directory nested more
than one level under the spine; a note whose filename needs escaping in a link label; or the
interaction with `exempt_roots` and `scan_excludes`, since the fixture declares both empty. A
regression in any of those passes the pinned comparison. Stated because a partial oracle that does
not say so is worse than none: it converts an unexamined case into an apparently examined one.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import NamedTuple

# ci/gates holds the shared library and is not a package; gates are run as
# scripts with their own directory on sys.path, so this module reproduces that
# one entry rather than growing a second copy of the helpers.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "gates"))

from _common import candidates, load_manifest, notes, repo_root  # noqa: E402

#: The tool a failure names. Recorded once; every message and the declaration
#: line in every generated file read it from here, so the name a contributor is
#: handed cannot disagree with the file that produced the index.
GENERATOR = "ci/gen/indexes.py"

#: One index per spine directory, at this filename inside it.
INDEX_NAME = "index.md"

DECLARATION = f"<!-- generated by {GENERATOR} -- do not edit by hand -->"
REGENERATE = f"<!-- regenerate: python3 {GENERATOR} --write -->"

#: Substring that identifies a file as claiming to be generated by this tool,
#: independent of the exact declaration wording. Used to catch a generated index
#: left behind for a directory that no longer has notes: it still declares a tool
#: that will never regenerate it, which is drift that a per-path comparison over
#: the *expected* set alone would never look at.
GENERATED_MARKER = "generated by"

#: Frontmatter every generated index carries, so the classification gate covers
#: it like any other note. `index` is in the declared `type` enumeration and
#: `none` satisfies the spine's prohibition on normative authority.
FRONTMATTER = (
    "---",
    "type: index",
    "status: current",
    "authority: none",
    "---",
)


class Finding(NamedTuple):
    """One drift verdict about one index path.

    kind is `missing`, `drift`, `undeclared` or `unowned`; line is the 1-based
    first differing line for `drift` and None where a line is meaningless.
    """

    kind: str
    index: str
    detail: str
    line: int | None


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def title_of(path: Path) -> str:
    """First H1 of a note, or its filename stem when it has none.

    The frontmatter block is skipped so a `---` fenced header cannot be mistaken
    for content, and the stem fallback keeps output stable for a note that has
    not been given a heading yet -- the spine has not been written, so that is
    the common case today rather than an edge one.
    """
    text = _read(path)
    if text is None:
        return path.stem
    lines = text.splitlines()
    start = 0
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                start = i + 1
                break
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip().rstrip("#").strip() or path.stem
    return path.stem


def _escape(text: str) -> str:
    """Keep a title containing brackets from breaking the link it labels."""
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def spine_notes(scan_root: Path, manifest: dict) -> tuple[list[str], bool]:
    """Spine notes that are index subjects, plus whether they came from the index.

    A generated index is not a subject of another generated index: it would make
    the output a function of itself, so one run could not be byte-identical to
    the next after a name change. Child directories are linked separately.
    """
    _paths, from_index = candidates(scan_root, manifest)
    subjects = [
        rel
        for rel in notes(scan_root, manifest, scopes=("spine",))
        if Path(rel).name != INDEX_NAME
    ]
    return subjects, from_index


def _directories(subjects: list[str], spine: str) -> dict[str, list[str]]:
    """Map each spine directory holding at least one subject to those subjects.

    The spine root is always present even when empty, because the spine root
    index is the entry into the vault and must exist for reachability. A
    directory with no notes of its own gets no index: an index of nothing is
    noise, and its absence is what makes a left-behind index detectable.
    """
    grouped: dict[str, list[str]] = {spine: []}
    for rel in subjects:
        grouped.setdefault(str(Path(rel).parent.as_posix()), []).append(rel)
    return {d: sorted(files) for d, files in sorted(grouped.items())}


def _children(directory: str, all_dirs: list[str]) -> list[str]:
    """Immediate child directories of `directory` that have an index."""
    prefix = directory + "/"
    return sorted(
        d
        for d in all_dirs
        if d.startswith(prefix) and "/" not in d[len(prefix) :]
    )


def render(scan_root: Path, directory: str, subjects: list[str], children: list[str]) -> str:
    """The exact bytes of one directory's index. Sorted, fixed, newline-terminated."""
    lines: list[str] = [*FRONTMATTER, "", DECLARATION, REGENERATE, "", f"# {directory}"]
    lines += ["", f"Generated index of the notes in `{directory}/`.", "", "## Notes", ""]
    if subjects:
        for rel in subjects:
            label = _escape(title_of(scan_root / rel))
            lines.append(f"- [{label}]({Path(rel).name})")
    else:
        lines.append("_No notes in this directory._")
    if children:
        lines += ["", "## Subdirectories", ""]
        for child in children:
            rel_link = f"{child[len(directory) + 1:]}/{INDEX_NAME}"
            lines.append(f"- [{child}]({rel_link})")
    return "\n".join(lines) + "\n"


def expected_indexes(scan_root: Path, manifest: dict) -> tuple[dict[str, str], bool]:
    """(index path -> expected bytes, from_index) for every spine directory."""
    subjects, from_index = spine_notes(scan_root, manifest)
    grouped = _directories(subjects, manifest["spine"])
    all_dirs = list(grouped)
    expected = {
        f"{directory}/{INDEX_NAME}": render(
            scan_root, directory, files, _children(directory, all_dirs)
        )
        for directory, files in grouped.items()
    }
    return expected, from_index


def _first_difference(expected: str, actual: str) -> int:
    """1-based first differing line, so a failure points at a line, not a file."""
    exp, act = expected.splitlines(), actual.splitlines()
    for i in range(max(len(exp), len(act))):
        if exp[i : i + 1] != act[i : i + 1]:
            return i + 1
    return min(len(exp), len(act)) + 1


def declares_generated(text: str) -> bool:
    """Whether a file states it is generated AND names the tool that produces it.

    Both halves are required by the requirement, and both are checked, because a
    file saying only "generated" leaves a reader with no command to run.
    """
    return GENERATED_MARKER in text and GENERATOR in text


def check(scan_root: Path, manifest: dict) -> tuple[list[Finding], dict[str, str], bool]:
    """Regenerate into memory and compare against what is tracked.

    Returns (findings, expected, from_index). Reads only; never writes. A stale
    index and a hand-edited one are the same byte comparison by construction --
    that is the point of comparing bytes rather than trusting a marker -- so the
    `undeclared` finding exists only to give the hand-edit case the more specific
    diagnosis it deserves alongside the drift.
    """
    expected, from_index = expected_indexes(scan_root, manifest)
    findings: list[Finding] = []

    for index in sorted(expected):
        want = expected[index]
        have = _read(scan_root / index)
        if have is None:
            findings.append(
                Finding(
                    "missing",
                    index,
                    "no tracked index for this spine directory -- generate and commit it",
                    None,
                )
            )
            continue
        if have != want:
            findings.append(
                Finding(
                    "drift",
                    index,
                    "tracked content is not byte-identical to a fresh regeneration",
                    _first_difference(want, have),
                )
            )
        if not declares_generated(have):
            findings.append(
                Finding(
                    "undeclared",
                    index,
                    "does not declare that it is generated and name its tool",
                    None,
                )
            )

    # A generated index whose directory no longer has notes is regenerated by
    # nothing, so a comparison over the expected set alone would never see it.
    for rel in notes(scan_root, manifest, scopes=("spine",)):
        if rel in expected:
            continue
        text = _read(scan_root / rel)
        if Path(rel).name == INDEX_NAME or (text and declares_generated(text)):
            findings.append(
                Finding(
                    "unowned",
                    rel,
                    "declares itself generated but indexes no spine directory",
                    None,
                )
            )

    return findings, expected, from_index


def write(scan_root: Path, manifest: dict) -> list[str]:
    """Write every expected index. The only mode that touches the filesystem."""
    expected, _ = expected_indexes(scan_root, manifest)
    written = []
    for index in sorted(expected):
        target = scan_root / index
        target.parent.mkdir(parents=True, exist_ok=True)
        if _read(target) != expected[index]:
            target.write_text(expected[index], encoding="utf-8")
            written.append(index)
    return written


def _parse_args(argv: list[str]) -> tuple[Path, bool]:
    scan_root: Path | None = None
    do_write = False
    rest = list(argv)
    while rest:
        arg = rest.pop(0)
        if arg == "--root":
            if not rest:
                raise SystemExit("--root requires a path")
            scan_root = Path(rest.pop(0)).resolve()
        elif arg == "--write":
            do_write = True
        elif arg == "--check":
            do_write = False
        else:
            raise SystemExit(f"unknown argument: {arg}")
    return (scan_root or repo_root()), do_write


def main(argv: list[str]) -> int:
    scan_root, do_write = _parse_args(argv)
    manifest = load_manifest(repo_root())
    if do_write:
        written = write(scan_root, manifest)
        for index in written:
            print(f"wrote {index}")
        print(f"{len(written)} index file(s) written")
        return 0
    findings, expected, _ = check(scan_root, manifest)
    for finding in findings:
        where = f":{finding.line}" if finding.line else ""
        print(f"{finding.kind}: {finding.index}{where}: {finding.detail}")
    print(f"{len(expected)} index file(s) expected, {len(findings)} finding(s)")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
