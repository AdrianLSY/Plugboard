#!/usr/bin/env python3
"""Generate the rule index: every rule note with its enforcement status.

docs/code-standards -- "Unenforced rules are quarantined" requires that a rule's
enforcement status be readable from the index WITHOUT opening the note, and that
the proportion carrying no gate be retrievable. Both are properties of a table,
so the table is generated rather than maintained: a hand-written index of
enforcement status is a second encoding of what the notes already say, and the
two drift in the direction that flatters the guide.

## What the violating input does not reach

`ci/generator-inputs/rule-index/` holds three rule notes -- one gated, one gate-planned, one named by
a gate from outside the rule directories -- and its pinned expectation catches any change to the
counts, the percentage, the row ordering, or the widening that holds a note a gate names. It does NOT
reach: the quarantine directory, since no preference note is present and the unenforced proportion is
therefore always 0%; a note with no `**Gate:**` line at all; or a rule note outside the spine, whose
relative link would be computed differently. A regression in any of those passes the comparison.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

# The rule set's other consumer is ci/gates/rule_gate_correspondence.py. Both
# resolve the same set, so the resolver is shared rather than reimplemented --
# the mirror of ci/gates/index_drift.py importing ci/gen/indexes.py, and
# permitted by the same clause of docs/code/languages/python.md.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "gates"))

from _common import rule_notes  # noqa: E402

HEADER = """---
type: index
status: current
authority: none
---

<!-- generated by ci/gen/rule_index.py -- do not edit by hand -->
<!-- regenerate: python3 ci/gen/rule_index.py --write -->

# Rule index

Every rule this repository states, with its enforcement status. A rule is **gated** (a check fails
the build today), **gate planned** (an obligation whose check is not built yet), or **preference**
(taste, quarantined, never a blocking objection).
"""


def repo_root() -> Path:
    here = Path(__file__).resolve()
    for c in [here.parent, *here.parents]:
        if (c / "ci" / "vault.json").is_file():
            return c
    raise SystemExit("could not locate ci/vault.json")


def build(root: Path) -> str:
    cfg = json.loads((root / "ci" / "vault.json").read_text(encoding="utf-8"))["code_standards"]
    rows, counts = [], {"gated": 0, "planned": 0, "preference": 0}
    for _rel, path in sorted(rule_notes(root, cfg).items()):
        text = path.read_text(encoding="utf-8")
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), path.stem)
        m = re.search(r"^\*\*Gate:\*\*\s*(.+)$", text, re.M)
        raw = (m.group(1) if m else "").strip()
        if re.match(r"none\b", raw, re.I):
            status, counts_key = "preference", "preference"
        elif re.match(r"planned\b", raw, re.I):
            status, counts_key = "gate planned", "planned"
        else:
            status, counts_key = "gated", "gated"
        counts[counts_key] += 1
        gate = re.search(r"`(ci/gates/[a-z_]+\.py)`", raw)
        rel = path.relative_to(root / "docs").as_posix()
        rows.append((title, status, gate.group(1) if gate else "—", rel))

    total = sum(counts.values())
    pct = (100 * counts["preference"] // total) if total else 0
    out = [HEADER, ""]
    out.append(f"**{total} rules** — {counts['gated']} gated, {counts['planned']} gate planned, "
               f"{counts['preference']} preference ({pct}% unenforced).")
    out += ["", "| rule | status | gate | note |", "|---|---|---|---|"]
    for title, status, gate, rel in sorted(rows, key=lambda r: (r[1] != "gated", r[0])):
        depth = rel.count("/")
        link = ("../" * 0) + rel
        out.append(f"| {title} | **{status}** | `{gate}` | [note]({link}) |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    # --root makes this generator runnable against a tree other than its own
    # repository, which is the whole of what makes it testable: a generator
    # verified only by re-running itself against the tree it produced is its own
    # oracle, and a wrong generator is consistently wrong.
    root = repo_root()
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    body = build(root)
    target = root / "docs" / "rule-index.md"
    if "--write" in argv:
        # Create the parent. Version control does not track an empty directory,
        # so a generator's input tree materialised from the index may not have
        # one -- which is how this surfaced: the tool ran in the working tree and
        # failed in a clean checkout.
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8")
        print(f"wrote {target.relative_to(root)}")
        return 0
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if current != body:
        print(f"DRIFT: {target.relative_to(root)} differs from a fresh regeneration")
        return 1
    print(f"[ok] {target.relative_to(root)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
