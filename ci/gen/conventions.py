#!/usr/bin/env python3
"""Generate the note-authoring channel from ci/vault.json.

RDV10: the conventions reach authors through TWO channels, because no single one
reaches both. openspec/config.yaml's `rules:` block is keyed per openspec
artifact, so it cannot express an obligation on a note -- and a note author never
opens it. This file is the other channel: a note the entry files link as their
first hop, generated from the same enumeration the gates key on, so the two
cannot state different conventions.

Generated rather than written for the reason every index here is: a hand-written
copy of what the manifest already says is a second encoding, and the two drift in
the direction that flatters the guide.

## What the violating input does not reach

`ci/generator-inputs/conventions/` holds two conventions, which is enough to observe ordering and the
count sentence. It does NOT reach: a convention whose `gate` names a module that does not exist; the
`_comment` handling, since the fixture's comment is a plain string where the repository's is an array;
or the cross-reference to the rule index, which the expectation pins as a link but cannot verify
resolves. A regression in any of those passes the comparison.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HEADER = """---
type: rule
status: current
authority: rationale
---

<!-- generated by ci/gen/conventions.py -- do not edit by hand -->
<!-- regenerate: python3 ci/gen/conventions.py --write -->

# Conventions for authoring a note

**Gate:** `ci/gates/authoring_channels.py`

Read this before writing or moving a note. Every line below is enforced by a gate named beside it, so
none of it is advice: a first draft that violates one of these fails the build rather than a review.

The same enumeration reaches the planning tool through `openspec/config.yaml`. A convention added to
the gates without reaching both channels fails.
"""


def repo_root() -> Path:
    here = Path(__file__).resolve()
    for c in [here.parent, *here.parents]:
        if (c / "ci" / "vault.json").is_file():
            return c
    raise SystemExit("could not locate ci/vault.json")


def build(root: Path) -> str:
    items = json.loads((root / "ci" / "vault.json").read_text(encoding="utf-8"))[
        "conventions"
    ]["items"]
    out = [HEADER, "", "| convention | what it requires | gate |", "|---|---|---|"]
    for cid in sorted(items):
        it = items[cid]
        out.append(f"| `{cid}` | {it['statement']} | `ci/gates/{it['gate']}.py` |")
    out += [
        "",
        "## If a gate refuses your note",
        "",
        "Its failure output names the rule note stating the rule it enforces. Read that note: it carries",
        "the defect the rule prevents and its citation. That is the cheapest moment to learn it.",
        "",
        f"All {len(items)} conventions above, plus every code rule and its enforcement status, are listed in",
        "[the rule index](../rule-index.md).",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    # --root makes this generator runnable against a tree other than its own
    # repository, which is the whole of what makes it testable: a generator
    # verified only by re-running itself against the tree it produced is its own
    # oracle, and a wrong generator is consistently wrong.
    root = repo_root()
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    body = build(root)
    target = root / "docs" / "method" / "conventions.md"
    if "--write" in argv:
        # Create the parent. Version control does not track an empty directory,
        # so a generator's input tree materialised from the index may not have
        # one -- which is how this surfaced: the tool ran in the working tree and
        # failed in a clean checkout.
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8")
        print(f"wrote {target.relative_to(root)}")
        return 0
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if current != body:
        print(f"DRIFT: {target.relative_to(root)} differs from a fresh regeneration")
        return 1
    print(f"[ok] {target.relative_to(root)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
